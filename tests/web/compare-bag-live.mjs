  page = await mobile.newPage(); observe(page);
  await page.goto(base + '/vi/products?category=iphone', { waitUntil: 'networkidle' });
  for (const product of phones.slice(0, 2)) await card(page, product).getByRole('button', { name: 'So sánh', exact: true }).tap();
  await expect(page.getByTestId('compare-dock')).toHaveCSS('animation-name', 'none');
  await page.screenshot({ path: 'artifacts/web/compare-bag/dock-mobile.png', fullPage: false });
  await page.getByRole('link', { name: 'Mở bảng so sánh', exact: true }).tap();
  const region = page.getByRole('region', { name: 'Bảng so sánh sản phẩm', exact: true });
