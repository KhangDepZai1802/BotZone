import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { base, client } from './live-api.mjs';
const actors=[], results=[], errors=[];
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1366,height:900},reducedMotion:'reduce'});
const page=await context.newPage();page.setDefaultTimeout(20000);page.on('pageerror',e=>errors.push(e.message));
try {
 const content=await client('content@botzone.local'), owner=await client('owner@botzone.local');actors.push(content,owner);
 const start=await content.get('/api/admin/landing');let revision=start.draft.revision;
 const seed=JSON.parse(await readFile('data/landing-demo.json','utf8'));
 const sections=seed.filter(s=>s.type==='hero'||s.type==='duo');
 assert.equal(sections.length,2);
 const common={productSlug:'',poster:'/media/phone-front.svg',model:'procedural:phone',colors:['#4B1527'],preset:'float',camera:5,tilt:8,light:2,speed:1,fold:0};
 sections.push({...common,id:'collection-edit',type:'collection',title:{vi:'Dành cho thế giới của bạn.',en:'Made for your world.'},subtitle:{vi:'Khám phá các dòng sản phẩm Apple, từ thế hệ trước đến lựa chọn mới.',en:'Explore Apple products, from earlier generations to new possibilities.'}});
 sections.push({...common,id:'benefits',type:'benefits',title:{vi:'An tâm trong từng trải nghiệm.',en:'Confidence in every experience.'},subtitle:{vi:'Thông tin rõ ràng. Hỗ trợ xuyên suốt hành trình.',en:'Clear information. Support throughout your journey.'}});
 const saved=await content.command('save_landing',{pageSlug:'home',revision,sections});revision=saved.revision;
 const published=await content.command('publish_landing',{pageSlug:'home',revision});revision=published.revision;
 const full=(await content.get('/api/admin/landing')).history[0];
 assert.deepEqual((await content.get('/api/landing')).sections,sections);
 await writeFile('data/landing-demo.json',JSON.stringify(sections,null,2)+'\n');
 results.push({publishedVersion:full.versionNo,revision,sections:sections.length});
 const forbidden=await owner.command('save_landing',{pageSlug:'home',revision,sections},crypto.randomUUID(),403);assert.equal(forbidden.error.code,'FORBIDDEN');
 const stale=await content.command('save_landing',{pageSlug:'home',revision:revision-1,sections},crypto.randomUUID(),409);assert.equal(stale.error.code,'STATE_CONFLICT');
 results.push('Owner cannot edit; stale draft revision rejected');
 const grant=await content.command('preview_landing',{revision,viewport:'mobile'});
 const draft=structuredClone(sections);draft[0].title.en='CMS isolation verification';draft[0].title.vi='Kiểm tra tách biệt bản nháp';
 revision=(await content.command('save_landing',{pageSlug:'home',revision,sections:draft})).revision;
 assert.deepEqual((await content.get('/api/landing')).sections,sections);
 const url=new URL(grant.url);const code=url.searchParams.get('code');
 await page.goto(base+url.pathname+url.search,{waitUntil:'networkidle'});
 await expect(page.locator('iframe')).toBeVisible();
 assert.equal(new URL(page.url()).searchParams.has('code'),false);
 const preview=await(await context.request.get(base+'/api/landing/preview')).json();
 assert.deepEqual(preview.sections,sections);assert.equal(preview.revision,revision-1);
 const frame=page.frameLocator('iframe');await expect(frame.getByRole('heading',{name:sections[0].title.vi,exact:true})).toBeVisible();
 assert.equal(await page.locator('iframe').evaluate(el=>Math.round(el.getBoundingClientRect().width)),390);
 const session=await(await context.request.get(base+'/api/session')).json();assert.equal(session.actor,null);
 const cookies=await context.cookies();const previewCookie=cookies.find(c=>c.name==='BotZone.Preview');assert.ok(previewCookie?.httpOnly);
 const csrf=(await(await context.request.get(base+'/api/auth/csrf')).json()).token;
 const replay=await context.request.post(base+'/api/landing/preview/redeem',{data:{code},headers:{'X-CSRF-TOKEN':csrf}});assert.ok([404,409].includes(replay.status()));
 await page.screenshot({path:'artifacts/web/cms-mobile-preview.png',fullPage:true});
 results.push('One-use preview bound to exact saved draft; HttpOnly preview cookie; no actor session; mobile iframe390px; URL code removed; replay denied');
 await content.command('revoke_landing_preview',{grantId:grant.grantId});
 assert.equal((await context.request.get(base+'/api/landing/preview')).status(),404);
 results.push('Explicit preview revocation enforced');
 revision=(await content.command('publish_landing',{pageSlug:'home',revision})).revision;
 assert.equal((await content.get('/api/landing')).sections[0].title.en,'CMS isolation verification');
 const restored=await content.command('restore_landing',{pageSlug:'home',revision,versionId:full.id});revision=restored.revision;
 assert.deepEqual((await content.get('/api/landing')).sections,sections);
 results.push({restoreCreatedNewVersion:(await content.get('/api/admin/landing')).history[0].versionNo,finalDraftRevision:revision});
 assert.deepEqual(errors,[]);console.log(JSON.stringify(results,null,2));
} catch(error) {results.push({failure:error.message});await page.screenshot({path:'artifacts/web/cms-failure.png',fullPage:true});throw error;}
finally {await writeFile('artifacts/web/cms-results.json',JSON.stringify({at:new Date().toISOString(),results,pageErrors:errors},null,2));await Promise.all(actors.map(a=>a.dispose()));await browser.close();}
